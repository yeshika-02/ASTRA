"""requirements-lock.txt must pin every declared dependency within its declared range.

The lock is generated by uv from requirements.txt minus torch (the command is in its
header). torch is installed separately from the PyTorch CPU index, so the lock must not
contain it or the CUDA wheels a PyPI torch would pull in.
"""

from __future__ import annotations

import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCK = ROOT / "requirements-lock.txt"


def _canonical(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def _declared() -> dict[str, str]:
    """Package name -> version specifier from requirements.txt."""
    declared = {}
    for line in (ROOT / "requirements.txt").read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            name, spec = re.match(r"([A-Za-z0-9_.-]+)\s*(.*)", line).groups()
            declared[_canonical(name)] = spec.strip()
    return declared


def _locked() -> list[tuple[str, str, str]]:
    """(name, version, environment marker) for each pinned line in the lock."""
    pins = []
    for line in LOCK.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        match = re.fullmatch(r"([A-Za-z0-9_.-]+)==([^\s;]+)\s*(?:;\s*(.*))?", line)
        if match is None:
            raise AssertionError(f"lock line is not an exact pin: {line!r}")
        name, version, marker = match.groups()
        pins.append((_canonical(name), version, marker or ""))
    return pins


class DependencyLockTests(unittest.TestCase):
    def test_every_line_is_an_exact_pin(self) -> None:
        self.assertGreater(len(_locked()), 20)

    def test_every_declared_dependency_except_torch_is_locked(self) -> None:
        locked = {name for name, _, _ in _locked()}
        missing = sorted(set(_declared()) - {"torch"} - locked)
        self.assertEqual(missing, [])

    def test_locked_versions_satisfy_the_declared_ranges(self) -> None:
        try:
            from packaging.specifiers import SpecifierSet
        except ImportError:
            self.skipTest("packaging not installed")
        declared = _declared()
        outside = [
            f"{name}=={version} not in {declared[name]!r}"
            for name, version, _ in _locked()
            if name in declared and version not in SpecifierSet(declared[name])
        ]
        self.assertEqual(outside, [])

    def test_torch_and_cuda_wheels_are_not_locked(self) -> None:
        unwanted = [name for name, _, _ in _locked() if name == "torch" or name.startswith(("nvidia-", "triton"))]
        self.assertEqual(unwanted, [])

    def test_header_records_the_generating_command(self) -> None:
        header = LOCK.read_text(encoding="utf-8").splitlines()[:2]
        self.assertIn("uv pip compile", header[1])
        self.assertIn("--exclude-newer", header[1])


if __name__ == "__main__":
    unittest.main()
